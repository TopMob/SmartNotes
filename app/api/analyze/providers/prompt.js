function toJsonBlock(value) {
  return JSON.stringify(value, null, 2)
}

export function buildAnalysisPrompt({ task, userContext, folders, notes }) {
  return [
    "You are a strict note analysis engine for SmartNotes.",
    "",
    "## Objective",
    "Analyze every provided note and return exactly one JSON object per note.",
    "The prompt context is intentionally narrowed to a small set of candidate folders.",
    "",
    "## Input Rules",
    "- The note belongs to one user only.",
    "- Folder selection is limited to the provided folder candidates.",
    "- If no candidate folder is a good match, return folderId as null.",
    "- Prefer specific folders over generic folders.",
    "- Preserve useful existing tags when they still match the note semantics.",
    "- Do not invent folders outside the candidate list.",
    "",
    "## Output Rules",
    "- Return only valid JSON.",
    "- Do not include markdown.",
    "- Do not include explanations.",
    "- Use only the allowed output fields.",
    "",
    "## Output Schema",
    "{",
    '  "id": "string",',
    '  "folderId": "string | null",',
    '  "userTags": ["string"],',
    '  "hiddenTags": ["string"],',
    '  "relevance": 0,',
    '  "resurfacingClass": "task | time-sensitive | idea | reference | archive-like"',
    "}",
    "",
    "## Constraints",
    "- userTags: 1 to 5 short user-facing tags.",
    "- hiddenTags: 5 to 15 semantic retrieval tags.",
    "- relevance: integer from 0 to 100.",
    "- The returned id must exactly match the input note id.",
    "- folderId must be one of the provided folder candidate ids or null.",
    "- Use the candidate folders as the complete allowed folder search space for this note.",
    "",
    "Task:",
    toJsonBlock(task),
    "",
    "User context:",
    toJsonBlock(userContext),
    "",
    "Folder candidates:",
    toJsonBlock(folders),
    "",
    "Notes:",
    toJsonBlock(notes)
  ].join("\n")
}
