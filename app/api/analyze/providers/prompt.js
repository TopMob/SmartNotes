    "Верни ровно один объект на каждую входную заметку. Нельзя пропускать заметки.",
    "",
    "Строгий формат каждого объекта:",
    "{",
    "  \"id\": \"noteId\",",
    "  \"folderId\": \"existingFolderId or null\",",
    "  \"userTags\": [\"...\"],",
    "  \"hiddenTags\": [\"...\"],",
    "  \"relevance\": 0",
    "}",
    "",
    "Разрешены только поля: id, folderId, userTags, hiddenTags, relevance.",
    "",
    "Правила folderId:",
    "1. Используй только folderId из переданного списка папок.",
    "2. Приоритет папок: name важнее description.",
    "3. description это дополнительная семантическая граница.",
    "4. При равной или почти равной близости папка с description сильнее папки без description.",
    "5. Generic folder penalty: общие папки (идеи, разное, misc, other, прочее) слабее специфичных тематических и проектных папок.",
    "6. currentFolderId это уже назначенная папка заметки.",
    "7. Если note.analyzed=true и note.currentFolderId не null, верни именно currentFolderId.",
